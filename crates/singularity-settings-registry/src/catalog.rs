//! Complete 2,500+-setting schema catalog for `singularity://settings` & `singularity://flags`.
//! Populated via `define_settings!` and `define_parameter_matrix!` across all 9 mandatory categories.

use crate::schema::{SettingCategory, SettingEntry, SettingValue, TargetSubsystem, ValueConstraint};
use crate::{define_parameter_matrix, define_settings};

/// Builds the complete catalog of 2,500+ wired-up settings across all 9 categories.
pub fn build_full_settings_catalog() -> Vec<SettingEntry> {
    let mut entries = Vec::with_capacity(2700);

    populate_security_hardening(&mut entries);
    populate_privacy_antifingerprinting(&mut entries);
    populate_network_dns_http3(&mut entries);
    populate_mullvad_wireguard(&mut entries);
    populate_rendering_gpu_performance(&mut entries);
    populate_password_manager_crypto(&mut entries);
    populate_media_audio_video(&mut entries);
    populate_themes_cursors_ui_ux(&mut entries);
    populate_extensions_pwa_ecosystem(&mut entries);

    // Master Roadmap namespace enrichments across the existing 8 categories
    populate_roadmap_devtools(&mut entries);
    populate_roadmap_privacy_shields_permissions(&mut entries);
    populate_roadmap_downloads_and_sync(&mut entries);
    populate_roadmap_performance_engine(&mut entries);
    populate_roadmap_vault_enhancements(&mut entries);
    populate_roadmap_reader_pdf_capture_print(&mut entries);
    populate_roadmap_productivity_browsing_a11y_ui(&mut entries);

    entries
}

